#!/usr/bin/env python3
"""Select audited GNU Unifont source drawings for the draft repertoire.

Input files must be the genuine drawing sources selected in source-manifest.json,
never built fonts or glyphs generated by hexfill/unihexfill. Blank graphic glyphs
are omitted; space separators are preserved. This tool does not make glyphs for
code points absent from its inputs.
"""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re

EXCLUDED_CATEGORIES = {"Cc", "Cf", "Cs", "Co", "Cn", "Zl", "Zp"}


def unicode_categories(path: Path) -> dict[int, str]:
    result: dict[int, str] = {}
    first: tuple[int, str] | None = None
    for raw in path.read_text(encoding="utf-8").splitlines():
        if not raw or raw.startswith("#"):
            continue
        fields = raw.split(";")
        cp, name, category = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            first = cp, category
        elif name.endswith(", Last>"):
            if first is None or first[1] != category:
                raise ValueError(f"Invalid range at U+{cp:04X}")
            result.update(dict.fromkeys(range(first[0], cp + 1), category))
            first = None
        else:
            result[cp] = category
    if first is not None:
        raise ValueError("Unterminated UnicodeData range")
    return result


def prepare(inputs: list[Path], ucd: Path, output: Path, prefer_first: bool = False) -> dict:
    categories = unicode_categories(ucd)
    glyphs: dict[int, str] = {}
    inventory = []
    excluded = Counter()
    excluded_codepoints: dict[str, list[str]] = {}
    duplicate_variants: list[dict] = []
    for path in inputs:
        file_count = 0
        for line_number, raw in enumerate(path.read_text(encoding="utf-8-sig").splitlines(), 1):
            if not raw or raw.startswith("#"):
                continue
            match = re.fullmatch(r"([0-9A-Fa-f]{4,6}):([0-9A-Fa-f]{32}|[0-9A-Fa-f]{64})", raw)
            if match is None:
                raise ValueError(f"Invalid HEX record: {path}:{line_number}")
            cp, bitmap = int(match[1], 16), match[2].upper()
            file_count += 1
            category = categories.get(cp, "Cn")
            reason = None
            if cp > 0x10FFFF or 0xD800 <= cp <= 0xDFFF:
                reason = "non_scalar"
            elif category in EXCLUDED_CATEGORIES:
                reason = f"category_{category}"
            elif int(bitmap, 16) == 0 and category != "Zs":
                reason = "blank_non_space"
            if reason:
                excluded[reason] += 1
                excluded_codepoints.setdefault(reason, []).append(f"U+{cp:04X}")
                continue
            if cp in glyphs and glyphs[cp] != bitmap:
                if not prefer_first:
                    raise ValueError(f"Conflicting drawings for U+{cp:04X}")
                duplicate_variants.append({"codepoint": f"U+{cp:04X}", "omitted_variant_source": str(path)})
                continue
            glyphs[cp] = bitmap
        inventory.append({"file": str(path), "sha256": hashlib.sha256(path.read_bytes()).hexdigest(), "records": file_count})
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("".join(f"{cp:04X}:{glyphs[cp]}\n" for cp in sorted(glyphs)), encoding="ascii")
    manifest = {
        "schema": 1,
        "input_files": inventory,
        "unicode_data": {"file": str(ucd), "sha256": hashlib.sha256(ucd.read_bytes()).hexdigest()},
        "clean_hex": {"file": str(output), "sha256": hashlib.sha256(output.read_bytes()).hexdigest(), "glyph_count": len(glyphs)},
        "excluded_record_counts": dict(excluded),
        "excluded_codepoints": excluded_codepoints,
        "duplicate_variant_policy": "Prefer the first input drawing" if prefer_first else "Conflicting drawings are errors",
        "duplicate_variants_omitted": duplicate_variants,
        "scope": "Audited source drawings only. Graphic characters and space separators in the pinned Unicode draft; no generated hex labels, reserved/private-use values or invisible non-space glyphs.",
    }
    output.with_suffix(".json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--hex", type=Path, nargs="+", required=True)
    parser.add_argument("--ucd", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--prefer-first", action="store_true", help="Choose the first input for conflicting regional variants")
    args = parser.parse_args()
    manifest = prepare(args.hex, args.ucd, args.output, args.prefer_first)
    print(json.dumps({"glyphs": manifest["clean_hex"]["glyph_count"], "excluded": manifest["excluded_record_counts"]}))


if __name__ == "__main__":
    main()
